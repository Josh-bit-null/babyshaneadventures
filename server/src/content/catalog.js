const SPIRAL = (i) => {
  const ring = Math.floor(i / 12) + 1
  const angle = (i % 12) * (Math.PI / 6) + ring * 0.4
  const radius = 4.2 + ring * 2.1
  return { x: Math.cos(angle) * radius, z: Math.sin(angle) * radius + 1.5, y: 0 }
}

export function slotForIndex(index) {
  const slot = PURCHASE_SLOTS[index] ?? SPIRAL(index - PURCHASE_SLOTS.length)
  const wobble = (index % 5) * 0.04
  return {
    x: Number((slot.x + wobble).toFixed(2)),
    y: Number(slot.y.toFixed(3)),
    z: Number((slot.z - wobble).toFixed(2)),
    ry: Number((((index * 37) % 360) * (Math.PI / 180)).toFixed(3)),
  }
}

